def build(ctx):
    """Router help text with the current target list appended."""
    targets = ctx.store.snapshot()
    if not targets:
        listing = ("Цели не зарегистрированы. Зарегистрируйте: "
                   "register_target(url=..., base=...) или connection=\"Srvr=...;Ref=...;\".")
    else:
        lines = [f"Цели ({ctx.store.path}):"]
        for target in targets:
            line = f"  {target.alias} — {target.url} — auth: {target.auth_kind()}"
            if target.edt:
                line += f" — EDT: {target.edt['project']}"
            if target.comment:
                line += f" — {target.comment}"
            lines.append(line)
        listing = "\n".join(lines)
    return f"{ROUTER_HELP}\n\n{listing}"
